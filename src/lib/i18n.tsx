const dict = { en, hi };

const STATUS: Record<Lang, Record<BookingStatus | JobStatus, string>> = {
  en: {
    requested: 'Requested', accepted: 'Accepted', rejected: 'Rejected', expired: 'Expired',
    cancelled: 'Cancelled', on_the_way: 'On the way', in_progress: 'In progress', completed: 'Completed',
    open: 'Open', booked: 'Booked',
  },
  hi: {
    requested: 'अनुरोध भेजा', accepted: 'स्वीकार', rejected: 'अस्वीकार', expired: 'समय समाप्त',
    cancelled: 'रद्द', on_the_way: 'रास्ते में', in_progress: 'काम जारी', completed: 'पूरा',
    open: 'खुला', booked: 'बुक',
  },
};

export type T = (key: TKey, vars?: Record<string, string | number>) => string;

type I18nValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: T;
  status: (s: BookingStatus | JobStatus) => string;
  catName: (c: Pick<Category, 'name_en' | 'name_hi'> | undefined | null) => string;
};

const I18nContext = createContext<I18nValue | null>(null);
const LANG_KEY = 'dinadena.lang';

export function readStoredLang(): Lang | null {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === 'en' || v === 'hi' ? v : null;
  } catch {
    return null;
  }
}

// Language lives in localStorage (works before login) and is mirrored to the profile.
const langListeners = new Set<() => void>();
function subscribeLang(cb: () => void) {
  langListeners.add(cb);
  return () => langListeners.delete(cb);
}

export function storeLang(l: Lang) {
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {}
  document.documentElement.lang = l;
  langListeners.forEach((cb) => cb());
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const lang = useSyncExternalStore(subscribeLang, () => readStoredLang() ?? 'en', () => 'en' as Lang);
  const setLang = storeLang;

  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    t: (key, vars) => {
      // `<key>_one` is the singular form, used when vars.n is 1.
      const one = vars?.n === 1 && `${key}_one` in en ? (`${key}_one` as TKey) : null;
      let s: string = dict[lang][one ?? key] ?? en[one ?? key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    status: (s) => STATUS[lang][s] ?? s,
    catName: (c) => (c ? (lang === 'hi' ? c.name_hi : c.name_en) : ''),
  }), [lang, setLang]);

  return <I18nContext value={value}>{children}</I18nContext>;
}

export function useI18n() {
  const v = useContext(I18nContext);
  if (!v) throw new Error('useI18n must be used inside I18nProvider');
  return v;
}
